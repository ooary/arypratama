export const slugify = (value: string) =>
  value
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90);

export const buildBrief = (post: any) => {
  const steps = post.slides.split("→").map((step: string) => step.trim()).filter(Boolean);

  return {
    objective: `Bikin konten ${post.format.toLowerCase()} yang nunjukin problem Excel real buat kerja/admin, lalu kasih solusi cepat lewat ${post.topic}.`,
    audience: "Pelamar kerja admin, staff sales/admin, fresh graduate, dan orang kantor yang pengen Excel sat-set.",
    structure: steps.map((step: string, index: number) => ({
      slide: index + 1,
      copy: index === 0 ? post.hook : step,
      visual: step,
    })),
    caption: `${post.hook}

${post.cta}`,
    hashtags: ["#excel", "#belajarexcel", "#testkerja", "#adminkantor", "#exceltips"],
    productionNotes: [
      "Pakai screenshot/simulasi Excel yang clean.",
      "Satu slide satu ide, jangan padat teks.",
      "Highlight cell/menu/shortcut yang sedang dipakai.",
      "Closing harus save-worthy, bukan cuma 'follow for more'.",
    ],
  };
};

export const scheduleRows = schedule.flatMap((day) =>
  day.posts.map((post, postIndex) => {
    const base = {
      ...post,
      date: day.date,
      day: day.day,
      slug: slugify(post.hook),
      accountSlug: post.account,
      order: Number(day.day.replace("Day ", "")) * 2 - (postIndex === 0 ? 1 : 0),
    };

    return {
      ...base,
      brief: buildBrief(base),
    };
  }),
);

export const getSchedulePost = (account: string, slug: string) =>
  scheduleRows.find((post) => post.accountSlug === account && post.slug === slug);
